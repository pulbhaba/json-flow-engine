// Generates src/integrations/generated/builtin.ts from integrations/builtin/*/integration.json.
// Every manifest is validated with the real validator (compiled into .registry-tool first), so an
// invalid manifest fails the build. `--check` verifies the committed file is up to date.
// Test/override options: --builtin-dir <dir>, --out <file>.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
function option(name, fallback) {
  const index = args.indexOf(name);
  return index === -1 ? fallback : resolve(args[index + 1] ?? "");
}
const builtinDir = option("--builtin-dir", join(root, "integrations/builtin"));
const out = option("--out", join(root, "src/integrations/generated/builtin.ts"));

const toolDir = join(root, ".registry-tool");
rmSync(toolDir, { recursive: true, force: true });
execFileSync(
  process.execPath,
  [
    join(root, "node_modules/typescript/bin/tsc"),
    "-p",
    join(root, "tsconfig.registry-tool.json"),
    "--noCheck",
  ],
  { cwd: root, stdio: "inherit" },
);
const { validateIntegrationManifest } = await import(
  pathToFileURL(join(toolDir, "integrations/validate.js")).href
);
rmSync(toolDir, { recursive: true, force: true });

const manifests = [];
const problems = [];
const entries = existsSync(builtinDir)
  ? readdirSync(builtinDir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
  : [];
for (const entry of entries) {
  const file = join(builtinDir, entry.name, "integration.json");
  if (!existsSync(file)) continue;
  let data;
  try {
    data = JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    problems.push(`${file}: invalid JSON: ${error.message}`);
    continue;
  }
  const result = validateIntegrationManifest(data);
  if (!result.ok) {
    for (const issue of result.issues) {
      problems.push(`${file}: ${issue.path || "/"}: ${issue.message}`);
    }
    continue;
  }
  if (result.manifest.provider !== entry.name) {
    problems.push(`${file}: provider "${result.manifest.provider}" must match "${entry.name}"`);
    continue;
  }
  manifests.push(result.manifest);
}
if (problems.length > 0) {
  console.error(`invalid built-in integrations:\n${problems.join("\n")}`);
  process.exit(1);
}

const body = manifests.length === 0 ? "[]" : JSON.stringify(manifests, null, 2);
const next = `// Generated by scripts/write-registry.js from integrations/builtin; do not edit.
import type { IntegrationManifest } from "../types.js";

export const builtinManifests: readonly IntegrationManifest[] = ${body};
`;

if (check) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== next) {
    console.error(`${out} is out of date; run npm run build:registry`);
    process.exit(1);
  }
  console.log(`${out} is up to date`);
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, next);
  console.log(`wrote ${out}`);
}
